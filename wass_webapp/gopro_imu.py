"""
WASS GoPro IMU Telemetry & Motion Dynamics Pipeline
===================================================
Extracts and synchronizes high-frequency IMU telemetry (accelerometer, gyroscope,
vessel attitude: pitch, roll, yaw, and heave acceleration) from GoPro MP4 recordings.
Integrates with vguzov/gopro_imu_extractor (goimuex) with an autonomous pure-Python
GPMF box parser and hydrodynamic wave-kinematics fallback.
"""

import os
